import bcrypt from 'bcryptjs';
import { query } from '../database/index.js';

export const ensureAdminUser = async () => {
  if (!process.env.DATABASE_URL) {
    return;
  }

  await query(
    `CREATE TABLE IF NOT EXISTS users (
      user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      first_name VARCHAR(100) NOT NULL,
      last_name VARCHAR(100) NOT NULL,
      username VARCHAR(254) UNIQUE NOT NULL,
      password TEXT NOT NULL,
      role VARCHAR(20) NOT NULL DEFAULT 'user'
    )`,
  );

  const passwordHash = await bcrypt.hash('cse340!', 10);
  await query(
    `INSERT INTO users (first_name, last_name, username, password, role)
     VALUES ('Admin', 'User', 'admin@example.com', $1, 'admin')
     ON CONFLICT (username) DO UPDATE
     SET role = 'admin',
         password = EXCLUDED.password`,
    [passwordHash],
  );
};

export const getAllUsers = async () => {
  const { rows } = await query(
    `SELECT user_id, first_name, last_name, username, role
     FROM users
     ORDER BY first_name, last_name, username`,
  );
  return rows;
};

export const getUserByUsername = async (username) => {
  const { rows } = await query(
    `SELECT user_id, first_name, last_name, username, password, role
     FROM users
     WHERE username = $1`,
    [username],
  );
  return rows[0] ?? null;
};

export const createUser = async (user) => {
  const passwordHash = await bcrypt.hash(user.password, 10);
  const { rows } = await query(
    `INSERT INTO users (first_name, last_name, username, password, role)
     VALUES ($1, $2, $3, $4, 'user')
     RETURNING user_id, first_name, last_name, username, role`,
    [user.first_name, user.last_name, user.username, passwordHash],
  );
  return rows[0];
};
