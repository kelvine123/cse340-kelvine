UPDATE service_projects AS project
SET location = project_seed.location
FROM (
  VALUES
    ('Learning, shared freely', 'Community Learning Center'),
    ('Care for our shared home', 'Riverside Community Garden'),
    ('Wellbeing within reach', 'Neighborhood Wellness Hub')
) AS project_seed (project_name, location)
WHERE project.project_name = project_seed.project_name
  AND project.location IS DISTINCT FROM project_seed.location;

INSERT INTO project_categories (project_id, category_id)
SELECT project.project_id, category.category_id
FROM (
  VALUES
    ('Learning, shared freely', 'Education'),
    ('Care for our shared home', 'Environment'),
    ('Wellbeing within reach', 'Health & wellbeing')
) AS project_category (project_name, category_name)
JOIN service_projects AS project
  ON project.project_name = project_category.project_name
JOIN categories AS category
  ON category.category_name = project_category.category_name
ON CONFLICT (project_id, category_id) DO NOTHING;

INSERT INTO project_categories (project_id, category_id)
SELECT project.project_id, category.category_id
FROM service_projects AS project
CROSS JOIN (
  SELECT MIN(category_id) AS category_id
  FROM categories
) AS category
WHERE NOT EXISTS (
  SELECT 1
  FROM project_categories AS project_category
  WHERE project_category.project_id = project.project_id
)
ON CONFLICT (project_id, category_id) DO NOTHING;

