BEGIN;

CREATE TABLE IF NOT EXISTS organizations (
  organization_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_name VARCHAR(150) NOT NULL UNIQUE,
  description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS categories (
  category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS service_projects (
  project_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_name VARCHAR(150) NOT NULL UNIQUE,
  description TEXT NOT NULL,
  organization_id INTEGER NOT NULL
    REFERENCES organizations (organization_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS project_categories (
  project_id INTEGER NOT NULL
    REFERENCES service_projects (project_id) ON DELETE CASCADE,
  category_id INTEGER NOT NULL
    REFERENCES categories (category_id) ON DELETE CASCADE,
  PRIMARY KEY (project_id, category_id)
);

CREATE INDEX IF NOT EXISTS project_categories_category_id_idx
  ON project_categories (category_id);

INSERT INTO categories (category_name)
VALUES
  ('Education'),
  ('Environment'),
  ('Health & wellbeing')
ON CONFLICT (category_name) DO NOTHING;

INSERT INTO organizations (organization_name, description)
VALUES
  (
    'Community Learning Collective',
    'A local organization expanding access to learning and mentorship.'
  ),
  (
    'Shared Earth Network',
    'A community group caring for natural spaces and a sustainable future.'
  ),
  (
    'Neighbor Wellbeing Alliance',
    'A local organization supporting care, connection, and healthy living.'
  )
ON CONFLICT (organization_name) DO NOTHING;

ALTER TABLE service_projects
  ADD COLUMN IF NOT EXISTS organization_id INTEGER
    REFERENCES organizations (organization_id) ON DELETE CASCADE;

UPDATE service_projects
SET organization_id = CASE project_name
  WHEN 'Learning, shared freely' THEN (
    SELECT organization_id
    FROM organizations
    WHERE organization_name = 'Community Learning Collective'
  )
  WHEN 'Care for our shared home' THEN (
    SELECT organization_id
    FROM organizations
    WHERE organization_name = 'Shared Earth Network'
  )
  WHEN 'Wellbeing within reach' THEN (
    SELECT organization_id
    FROM organizations
    WHERE organization_name = 'Neighbor Wellbeing Alliance'
  )
  ELSE (
    SELECT MIN(organization_id)
    FROM organizations
  )
END
WHERE organization_id IS NULL;

ALTER TABLE service_projects
  ALTER COLUMN organization_id SET NOT NULL;

INSERT INTO service_projects (project_name, description, organization_id)
