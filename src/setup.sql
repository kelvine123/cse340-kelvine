WHERE contact_email IS NULL OR BTRIM(contact_email) = '';

ALTER TABLE organizations
  ALTER COLUMN contact_email SET NOT NULL;

CREATE TABLE IF NOT EXISTS categories (
  category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS service_projects (
  project_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_name VARCHAR(150) NOT NULL UNIQUE,
  description TEXT NOT NULL,
  location VARCHAR(255) NOT NULL,
  project_date DATE,
  organization_id INTEGER NOT NULL
    REFERENCES organizations (organization_id) ON DELETE CASCADE
);

ALTER TABLE service_projects
  ADD COLUMN IF NOT EXISTS location VARCHAR(255);

ALTER TABLE service_projects
  ADD COLUMN IF NOT EXISTS project_date DATE;

UPDATE service_projects
SET location = CASE project_name
  WHEN 'Learning, shared freely' THEN 'Community Learning Center'
  WHEN 'Care for our shared home' THEN 'Riverside Community Garden'
  WHEN 'Wellbeing within reach' THEN 'Neighborhood Wellness Hub'
  ELSE 'Community center'
END
WHERE location IS NULL OR BTRIM(location) = '';

ALTER TABLE service_projects
  ALTER COLUMN location SET NOT NULL;

WITH undated_projects AS (
  SELECT project_id,
         CURRENT_DATE + (ROW_NUMBER() OVER (ORDER BY project_id) - 1)::INTEGER AS project_date
  FROM service_projects
  WHERE project_date IS NULL
)
UPDATE service_projects AS project
SET project_date = undated_projects.project_date
FROM undated_projects
WHERE project.project_id = undated_projects.project_id;

ALTER TABLE service_projects
  ALTER COLUMN project_date SET NOT NULL;

CREATE TABLE IF NOT EXISTS project_categories (
  project_id INTEGER NOT NULL
    REFERENCES service_projects (project_id) ON DELETE CASCADE,
  category_id INTEGER NOT NULL
    REFERENCES categories (category_id) ON DELETE CASCADE,
  PRIMARY KEY (project_id, category_id)
);

CREATE INDEX IF NOT EXISTS project_categories_category_id_idx
  ON project_categories (category_id);

