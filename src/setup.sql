      FROM organizations
      WHERE organization_name = 'Community Learning Collective'
    )
  ),
  (
    'Care for our shared home',
    'Care for natural spaces and build a sustainable future.',
    (
      SELECT organization_id
      FROM organizations
      WHERE organization_name = 'Shared Earth Network'
    )
  ),
  (
    'Wellbeing within reach',
    'Make care, connection, and healthy living more accessible.',
    (
      SELECT organization_id
      FROM organizations
      WHERE organization_name = 'Neighbor Wellbeing Alliance'
    )
  )
ON CONFLICT (project_name) DO NOTHING;

INSERT INTO project_categories (project_id, category_id)
SELECT project.project_id, category.category_id
FROM (
  VALUES
    ('Learning, shared freely', 'Education'),
    ('Care for our shared home', 'Environment'),
    ('Wellbeing within reach', 'Health & wellbeing')
) AS project_category (project_name, category_name)
JOIN service_projects AS project
  ON project.project_name = project_category.project_name
JOIN categories AS category
  ON category.category_name = project_category.category_name
ON CONFLICT (project_id, category_id) DO NOTHING;

COMMIT;
